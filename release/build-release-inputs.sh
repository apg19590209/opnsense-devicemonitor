#!/bin/sh
# Regenerate release/release-inputs.sha256 for the current payload version.
#
#   build-release-inputs.sh
#
# The payload version is read from the shipped defaults.json, so the manifest this file
# pins and the version the installer enforces cannot drift apart. Rows are sorted by path
# and use the same "<sha256> <relative path>" shape install-unattended.sh and
# verify-release-inputs.sh read.
set -eu
LC_ALL=C
export LC_ALL

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)
REPO=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd -P)
cd "$REPO"

digest() {
    if [ -n "${DM_SHA256:-}" ]; then
        $DM_SHA256 "$1"
    elif command -v sha256 >/dev/null 2>&1; then
        sha256 -q "$1"
    else
        sha256sum "$1" | awk '{print $1}'
    fi
}

DEFAULTS=src/opnsense/mvc/app/models/OPNsense/DeviceMonitor/defaults.json
VERSION=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["version"])' "$DEFAULTS")
OUT=release/release-inputs.sha256

# Everything the installer executes or trusts as data. install-unattended.sh itself is the
# verifier and is not self-referential here; it pins this file instead.
cat <<EOF > "$OUT"
# Pinned install inputs for the Device Monitor payload (Decision 62).
# Generated by release/build-release-inputs.sh; do not edit by hand.
EOF

{
    echo "release/v${VERSION}-runtime.manifest"
    echo "release/prune-plan.sh"
    echo "release/legacy-targets.txt"
    echo "release/merge-opnsense-catalog.sh"
} | sort -u | while read -r path; do
    [ -f "$path" ] || { echo "build-release-inputs: missing $path" >&2; exit 1; }
    printf '%s %s\n' "$(digest "$path")" "$path"
done >> "$OUT"

echo "pinned inputs   : $(grep -vc '^#' "$OUT" | tr -d ' ')"
echo "inputs sha256   : $(digest "$OUT")"
echo "payload version : $VERSION"

