#!/bin/sh
# Build release/legacy-targets.txt: the trusted legacy ownership evidence for pruning.
#
#   build-legacy-evidence.sh [TAG...]
#
# Each row is "<sha256> <absolute target>" taken from a *published release manifest* at a
# git tag. The installer only prunes a path that no record covers when the file on disk
# still hashes to one of these published digests inside an approved namespace, so the
# evidence is exactly "a Device Monitor release shipped this file with this content".
#
# Tags without a runtime manifest are skipped: v2.8 predates the manifest format, and
# v2.12 is a source baseline that was never installable (README, "there is no 2.12
# release"). The current release is deliberately absent: the installer records what it
# installs itself, so its own manifest is not legacy evidence for the next run.
set -eu
LC_ALL=C
export LC_ALL

PROG=build-legacy-evidence.sh

digest() {
    if [ -n "${DM_SHA256:-}" ]; then
        $DM_SHA256 "$1"
    elif command -v sha256 >/dev/null 2>&1; then
        sha256 -q "$1"
    else
        sha256sum "$1" | awk '{print $1}'
    fi
}

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)
REPO=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd -P)
OUT=${1:-}
if [ -n "$OUT" ] && [ -d "$OUT" ]; then
    echo "usage: build-legacy-evidence.sh [OUTPUT_FILE]" >&2
    exit 2
fi
[ -n "$OUT" ] || OUT=$SCRIPT_DIR/legacy-targets.txt

cd "$REPO"

DEFAULT_TAGS="v2.9 v2.10 v2.11-patch1 v2.13 v2.13.1 v2.13.2"
TAGS=${DM_LEGACY_TAGS:-$DEFAULT_TAGS}

work=$(mktemp -d "${TMPDIR:-/tmp}/dm_legacy.XXXXXX")
trap 'rm -rf "$work"' EXIT

: > "$work/rows"
: > "$work/sources"
for tag in $TAGS; do
    if ! git rev-parse -q --verify "refs/tags/$tag" >/dev/null 2>&1; then
        echo "build-legacy-evidence: no such tag: $tag" >&2
        exit 1
    fi
    manifests=$(git ls-tree --name-only "$tag" release/ | grep -E '^release/.*-runtime\.manifest$' || :)
    if [ -z "$manifests" ]; then
        continue
    fi
    for manifest in $manifests; do
        printf '%s@%s\n' "$tag" "$manifest" >> "$work/sources"
        git show "$tag:$manifest" | awk -v tag="$tag" -v manifest="$manifest" '
            NF == 4 { print $1, $4 }
            NF != 0 && NF != 4 { printf "build-legacy-evidence: bad row in %s@%s: %s\n", tag, manifest, $0 > "/dev/stderr"; exit 1 }
        ' >> "$work/rows" || exit 1
    done
done

{
    echo '# Legacy ownership evidence for release/prune-plan.sh (Decision 62).'
    echo '#'
    echo '# Generated by release/build-legacy-evidence.sh; do not edit by hand.'
    echo '# Format: <sha256> <absolute installed target>. One row per (digest, target) pair'
    echo '# published by a historical Device Monitor release manifest.'
    echo '#'
    echo '# Sources:'
    while read -r source; do
        echo "#   $source"
    done < "$work/sources"
    sort -u "$work/rows"
} > "$OUT"

echo "legacy targets: $(grep -vc '^#' "$OUT" | tr -d ' ') from $(wc -l < "$work/sources" | tr -d ' ') manifest(s)"
echo "sha256: $(digest "$OUT")"

